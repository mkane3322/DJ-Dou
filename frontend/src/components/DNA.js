// RADAR CHART
// ══════════════════════════════════════════════════════════════════════════════
export function RadarChart({ data = [], size = 300 }) {
  const svgRef = useRef(null);

  useEffect(() => {
    if (!data.length || !svgRef.current) return;
    const svg    = d3.select(svgRef.current);
    svg.selectAll('*').remove();

    const margin = 46;
    const r      = size / 2 - margin;
    const cx     = size / 2;
    const total  = data.length;
    const slice  = (Math.PI * 2) / total;
    const rScale = d3.scaleLinear().range([0, r]).domain([0, 1]);
    const g      = svg.attr('width', size).attr('height', size).append('g').attr('transform', `translate(${cx},${cx})`);

    // Glow filter
    const defs = svg.append('defs');
    const flt  = defs.append('filter').attr('id', 'glow');
    flt.append('feGaussianBlur').attr('stdDeviation', '4').attr('result', 'cb');
    const fm = flt.append('feMerge');
    fm.append('feMergeNode').attr('in', 'cb');
    fm.append('feMergeNode').attr('in', 'SourceGraphic');

    // Grid
    for (let lvl = 1; lvl <= 5; lvl++) {
      g.append('circle').attr('r', (r / 5) * lvl).attr('fill', 'none').attr('stroke', 'rgba(168,85,247,0.1)').attr('stroke-width', 1);
    }

    // Axes + labels
    data.forEach((d, i) => {
      const a  = slice * i - Math.PI / 2;
      const x  = rScale(1) * Math.cos(a);
      const y  = rScale(1) * Math.sin(a);
      const lx = (r + 22) * Math.cos(a);
      const ly = (r + 22) * Math.sin(a);
      g.append('line').attr('x1', 0).attr('y1', 0).attr('x2', x).attr('y2', y).attr('stroke', 'rgba(168,85,247,0.2)').attr('stroke-width', 1);
      g.append('text').attr('x', lx).attr('y', ly).attr('text-anchor', 'middle').attr('dominant-baseline', 'middle').attr('fill', '#9d8fc4').attr('font-size', '11px').attr('font-family', "'Syne',sans-serif").attr('font-weight', '600').text(d.axis);
    });

    // Blob
    const line = d3.lineRadial().radius((d) => rScale(d.value)).angle((_, i) => i * slice).curve(d3.curveLinearClosed);
    const blob = g.append('g');
    blob.append('path').datum(data).attr('d', line).attr('fill', 'rgba(168,85,247,0.18)').attr('stroke', 'none');
    blob.append('path').datum(data).attr('d', line).attr('fill', 'none').attr('stroke', '#a855f7').attr('stroke-width', 2).attr('filter', 'url(#glow)');

    data.forEach((d, i) => {
      const a = slice * i - Math.PI / 2;
      g.append('circle').attr('cx', rScale(d.value) * Math.cos(a)).attr('cy', rScale(d.value) * Math.sin(a)).attr('r', 4).attr('fill', '#a855f7').attr('stroke', '#f1eeff').attr('stroke-width', 1.5).attr('filter', 'url(#glow)');
    });
  }, [data, size]);

  return <div style={{ display:'flex', justifyContent:'center' }}><svg ref={svgRef} /></div>;
}

