// SEEDS MANAGER
// ══════════════════════════════════════════════════════════════════════════════
export function SeedsManager() {
  const { seeds, seedSpotifyIds, loading, adding, addSeed, removeSeed } = useSeeds();

  const handleAdd = async (track) => {
    try { await addSeed(track.spotifyId); } catch { /* error surfaced by hook */ }
  };

  return (
    <div style={{ display:'flex', flexDirection:'column', gap:'1rem' }}>
      <div style={{ display:'flex', alignItems:'center', justifyContent:'space-between' }}>
        <div>
          <h3 style={{ fontWeight:700, fontSize:'1rem' }}>Seed Tracks</h3>
          <p style={{ color:'var(--text-secondary)', fontSize:'0.8rem' }}>Anchors for your SoundDNA. Up to 10.</p>
        </div>
        <span style={{ fontFamily:'var(--mono)', fontSize:'0.72rem', color:'var(--accent)', background:'rgba(168,85,247,0.1)', border:'1px solid var(--border-bright)', padding:'0.2rem 0.6rem', borderRadius:'var(--radius-full)' }}>
          {seeds.length} / 10
        </span>
      </div>

      <TrackSearchInput onSelect={handleAdd} seedIds={seedSpotifyIds} placeholder="Search to add a seed track…" />

      {loading ? (
        <div style={{ display:'flex', flexDirection:'column', gap:'8px' }}>
          {[1,2,3].map((i) => <div key={i} className="skeleton" style={{ height:52 }} />)}
        </div>
      ) : seeds.length === 0 ? (
        <p style={{ color:'var(--text-muted)', fontSize:'0.875rem', textAlign:'center', padding:'1.5rem 0' }}>🌱 No seeds yet — search above to add some.</p>
      ) : (
        <div style={{ display:'flex', flexDirection:'column', gap:'8px' }}>
          {seeds.map((s) => {
            const t = s.track;
            if (!t) return null;
            return (
              <div key={s.id} style={{ display:'flex', alignItems:'center', gap:'10px', padding:'10px', borderRadius:'var(--radius)', background:'var(--bg-raised)', border:'1px solid var(--border)' }}>
                {t.albumArt
                  ? <img src={t.albumArt} alt="" style={{ width:40, height:40, borderRadius:'var(--radius-sm)', objectFit:'cover', flexShrink:0 }} />
                  : <div style={{ width:40, height:40, borderRadius:'var(--radius-sm)', background:'var(--bg-overlay)', display:'flex', alignItems:'center', justifyContent:'center', flexShrink:0 }}>🎵</div>
                }
                <div style={{ flex:1, minWidth:0 }}>
                  <div style={{ fontWeight:600, fontSize:'0.875rem', overflow:'hidden', textOverflow:'ellipsis', whiteSpace:'nowrap' }}>{t.title}</div>
                  <div style={{ color:'var(--text-secondary)', fontSize:'0.75rem', overflow:'hidden', textOverflow:'ellipsis', whiteSpace:'nowrap' }}>{t.artist}</div>
                </div>
                <button onClick={() => removeSeed(t._id || t.id)} style={{ color:'var(--text-muted)', fontSize:'0.8rem', padding:'4px 8px', borderRadius:'var(--radius-sm)' }}>✕</button>
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
}
