// DNA BREAKDOWN — all 13 feature bars, collapsible
// ══════════════════════════════════════════════════════════════════════════════
export function DNABreakdown({ dnaVector }) {
  const [expanded, setExpanded] = useState(false);
  if (!dnaVector?.length) return null;
  const values = Object.fromEntries(FEATURE_META.map((m, i) => [m.key, dnaVector[i] ?? 0]));
  const visible = expanded ? FEATURE_META : FEATURE_META.slice(0, 6);

  return (
    <div>
      <h3 style={{ fontWeight:700, fontSize:'1rem', marginBottom:'1rem' }}>All 13 Dimensions</h3>
      <div style={{ display:'flex', flexDirection:'column', gap:'0.75rem' }}>
        {visible.map((meta) => <FeatureBar key={meta.key} meta={meta} value={values[meta.key]} />)}
      </div>
      <button onClick={() => setExpanded((e) => !e)} style={{ marginTop:'0.75rem', color:'var(--accent)', fontFamily:'var(--mono)', fontSize:'0.72rem', cursor:'pointer', padding:0 }}>
        {expanded ? '↑ Show less' : `↓ Show all ${FEATURE_META.length} dimensions`}
      </button>
    </div>
  );
}

